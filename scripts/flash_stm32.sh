#!/bin/bash
# ==============================================================================
# Скрипт: flash_stm32.sh
# Описание: Прошивка STM32F103 через UART с использованием встроенного 
#           системного загрузчика (System Memory Bootloader).
#           Автоматически переводит МК в режим загрузки через линии RTS/DTR.
# ==============================================================================

# Включаем строгий режим выполнения (ошибка при неинициализированных переменных и т.д.)
set -e

# ------------------------------------------------------------------------------
# Проверка входных аргументов
# ------------------------------------------------------------------------------
if [ "$#" -lt 3 ]; then
    echo "Ошибка: Недостаточно аргументов."
    echo "Использование: $0 <ПОРТ> <СКОРОСТЬ> <ФАЙЛ_ПРОШИВКИ>"
    echo "Пример: $0 /dev/ttyCH343USB0 115200 build/firmware.bin"
    exit 1
fi

PORT=$1
BAUD_RATE=$2
FIRMWARE_FILE=$3

# ------------------------------------------------------------------------------
# Проверка наличия файла прошивки
# ------------------------------------------------------------------------------
if [ ! -f "$FIRMWARE_FILE" ]; then
    echo "Ошибка: Файл прошивки '$FIRMWARE_FILE' не найден!"
    exit 1
fi

# ------------------------------------------------------------------------------
# Проверка доступности порта
# ------------------------------------------------------------------------------
if [ ! -c "$PORT" ]; then
    echo "Ошибка: Порт '$PORT' не существует или нет прав доступа."
    echo "Проверьте подключение USB-UART и права пользователя (группа dialout)."
    exit 1
fi

echo "========================================================================"
echo " Начало прошивки STM32F103"
echo " Порт:        $PORT"
echo " Скорость:    $BAUD_RATE бод"
echo " Файл:        $FIRMWARE_FILE"
echo " Размер:      $(stat -c%s "$FIRMWARE_FILE") байт"
echo "========================================================================"

# ------------------------------------------------------------------------------
# Параметры последовательности инициализации (-i)
# ------------------------------------------------------------------------------
# Формат флага -i: последовательность состояний RTS и DTR.
# Стандартная схема подключения:
# - RTS -> RESET (активный уровень LOW, т.е. при Assert RTS = 0В на пине RESET)
# - DTR -> BOOT0 (через инвертор или транзистор, либо напрямую, если DTR=3.3V)
# 
# Последовательность RTS,DTR,DTR,RTS означает:
# 1. Assert RTS, Deassert DTR  -> Сброс МК, BOOT0=0
# 2. Assert RTS, Assert DTR    -> Сброс МК, BOOT0=1 (переход в Bootloader)
# 3. Deassert RTS, Assert DTR  -> Снятие сброса, МК стартует в Bootloader
# 4. Deassert RTS, Deassert DTR -> Возврат линий в исходное состояние
#
# Если ваша аппаратная схема использует прямое подключение без инверторов 
# (DTR напрямую на BOOT0, RTS напрямую на NRST), последовательность может 
# потребоваться скорректировать (например, DTR,RTS,RTS,DTR).
BOOT_SEQUENCE="RTS,DTR,DTR,RTS"

# ------------------------------------------------------------------------------
# Запуск stm32flash
# ------------------------------------------------------------------------------
# Флаги:
# -w  : записать файл в Flash
# -v  : проверить (verify) записанные данные
# -g  : запустить программу (Go) по адресу 0x08000000 (начало Flash STM32F1)
# -b  : скорость UART
# -i  : последовательность управления RTS/DTR для входа/выхода из bootloader
# -S  : (опционально) адрес и размер, если нужно переопределить, но обычно не требуется

stm32flash -w "$FIRMWARE_FILE" \
           -v \
           -g 0x08000000 \
           -b "$BAUD_RATE" \
           -i "$BOOT_SEQUENCE" \
           "$PORT"

EXIT_CODE=$?

echo "========================================================================"
if [ $EXIT_CODE -eq 0 ]; then
    echo " УСПЕХ: Прошивка успешно загружена и верифицирована!"
else
    echo " ОШИБКА: Не удалось прошить устройство (код ошибки: $EXIT_CODE)."
    echo " Возможные причины:"
    echo " 1. Неверная последовательность RTS/DTR (проверьте схему обвязки)."
    echo " 2. Пин BOOT0 не подтянут к земле при обычном запуске."
    echo " 3. Помехи на линиях UART TX/RX."
fi
echo "========================================================================"

exit $EXIT_CODE
